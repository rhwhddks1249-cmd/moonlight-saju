COLORS = {"목": "초록", "화": "빨강", "토": "노랑", "금": "흰색", "수": "검정"}
LABELS = ["전체", "재물", "애정", "직장", "건강"]
GOD_BASE = {"비견": 3, "겁재": 2, "식신": 4, "상관": 3, "편재": 4,
            "정재": 4, "편관": 2, "정관": 4, "편인": 3, "정인": 5}


def _score(day_stem, d, label, god):
    h = hashlib.sha256(f"{day_stem}{d.isoformat()}{label}".encode()).digest()[0]
    return max(1, min(5, GOD_BASE[god] + (h % 3) - 1))


def today_fortune(day_stem, today=None):
    me = normalize_stem(day_stem)
    if me is None:
        raise ValueError("일간을 확인할 수 없습니다.")
    d = today or datetime.datetime.now(
        datetime.timezone(datetime.timedelta(hours=9))).date()
    pillar, s_idx, b_idx = day_pillar(d)
    god = ten_god(me, s_idx)
    t = TEXT[god]
    elem = ELEMENTS[s_idx // 2]
    return {
        "date": d.isoformat(),
        "day_pillar": pillar,
        "my_stem": STEMS[me],
        "ten_god": god,
        "headline": t[0],
        "sections": [
            {"label": lb, "stars": _score(STEMS[me], d, lb, god), "text": t[i + 1]}
            for i, lb in enumerate(LABELS)
        ],
        "advice": t[6],
        "lucky_color": COLORS[elem],
        "lucky_number": (int(hashlib.sha256(f"{STEMS[me]}{d}n".encode()).digest()[0]) % 9) + 1,
    }
