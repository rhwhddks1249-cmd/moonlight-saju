"""오늘의 운세: 오늘 일진(日辰)과 내 일간(日干)의 십성 관계로 풀이한다."""
import datetime
import hashlib

STEMS = "갑을병정무기경신임계"
BRANCHES = "자축인묘진사오미신유술해"
HANJA_STEMS = "甲乙丙丁戊己庚辛壬癸"
ELEMENTS = ["목", "화", "토", "금", "수"]
_BASE = datetime.date(1949, 10, 1)  # 갑자일


def day_pillar(d):
    """양력 날짜의 일주(예: '갑자')와 천간·지지 인덱스."""
    n = (d - _BASE).days % 60
    return STEMS[n % 10] + BRANCHES[n % 12], n % 10, n % 12


def normalize_stem(s):
    s = (s or "").strip()[:1]
    if s in STEMS:
        return STEMS.index(s)
    if s in HANJA_STEMS:
        return HANJA_STEMS.index(s)
    return None


def ten_god(me, other):
    """내 일간(me)에 대한 other 천간의 십성."""
    me_e, me_p = me // 2, me % 2
    o_e, o_p = other // 2, other % 2
    same = me_p == o_p
    diff = (o_e - me_e) % 5
    if diff == 0:
        return "비견" if same else "겁재"
    if diff == 1:
        return "식신" if same else "상관"
    if diff == 2:
        return "편재" if same else "정재"
    if diff == 3:
        return "편관" if same else "정관"
    return "편인" if same else "정인"


